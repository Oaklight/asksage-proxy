"""Tests for the legacy YAML → gateway JSONC translation."""

from __future__ import annotations

import json
from datetime import datetime, timezone

import pytest

from asksage_proxy import migrate

STAMP = datetime(2026, 11, 6, 12, 0, tzinfo=timezone.utc)


def parse_jsonc(text: str) -> dict:
    """Parse a rendered document by dropping its ``//`` comment lines."""
    body = "\n".join(
        line for line in text.splitlines() if not line.lstrip().startswith("//")
    )
    return json.loads(body)


def test_single_key_maps_to_one_provider() -> None:
    legacy = {
        "host": "0.0.0.0",
        "port": 50733,
        "api_keys": [{"key": "k-1"}],
        "asksage_server_base_url": "https://api.asksage.anl.gov/server",
        "timeout_seconds": 30.0,
    }

    config = migrate.build_config(legacy, model_ids=["gpt-4.1"], generated_at=STAMP)

    assert config["providers"] == {
        "asksage": {
            "shim": "asksage--chat_completions",
            "base_url": "https://api.asksage.anl.gov/server/openai/v1",
            "api_key": "k-1",
        }
    }
    assert config["models"] == {"gpt-4.1": "asksage"}
    assert config["shims"] == {"presets": ["asksage"]}
    assert config["server"] == {
        "host": "0.0.0.0",
        "port": 50733,
        "upstream_timeout": 30.0,
    }


def test_legacy_single_api_key_field_is_accepted() -> None:
    config = migrate.build_config({"api_key": "k-legacy"}, model_ids=["m"])

    assert list(config["providers"]) == ["asksage"]
    assert config["providers"]["asksage"]["api_key"] == "k-legacy"


def test_several_keys_become_weighted_lanes() -> None:
    legacy = {
        "api_keys": [
            {"key": "k-1", "weight": 3.0, "name": "primary"},
            {"key": "k-2", "weight": 1.0, "name": "backup"},
        ]
    }

    config = migrate.build_config(legacy, model_ids=["m"], generated_at=STAMP)

    assert list(config["providers"]) == ["asksage-primary", "asksage-backup"]
    assert config["models"]["m"] == {
        "providers": [
            {"name": "asksage-primary", "weight": 3},
            {"name": "asksage-backup", "weight": 1},
        ]
    }


def test_fractional_and_invalid_weights_are_floored_at_one() -> None:
    keys = migrate.normalize_keys(
        {
            "api_keys": [
                {"key": "a", "weight": 0.4},
                {"key": "b", "weight": "not-a-number"},
                {"key": "c", "weight": float("nan")},
                {"key": "d"},
            ]
        }
    )

    assert [key.weight for key in keys] == [1, 1, 1, 1]


def test_entries_without_a_key_are_dropped() -> None:
    keys = migrate.normalize_keys(
        {"api_keys": [{"weight": 2}, {"key": ""}, {"key": " "}, "k-literal"]}
    )

    assert [key.key for key in keys] == ["k-literal"]


def test_duplicate_names_are_disambiguated() -> None:
    keys = migrate.normalize_keys(
        {"api_keys": [{"key": "a", "name": "lab"}, {"key": "b", "name": "lab"}]}
    )

    assert migrate.provider_names(keys) == ["asksage-lab", "asksage-lab-2"]


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        ("https://h/server/", "https://h/server/openai/v1"),
        ("https://h/server", "https://h/server/openai/v1"),
    ],
)
def test_base_url_normalisation(raw: str, expected: str) -> None:
    config = migrate.build_config(
        {"api_key": "k", "asksage_server_base_url": raw}, model_ids=[]
    )

    assert config["providers"]["asksage"]["base_url"] == expected


def test_render_is_stable_and_parses_back() -> None:
    legacy = {"api_key": "k", "port": 8080}
    config = migrate.build_config(legacy, model_ids=["m"], generated_at=STAMP)

    first = migrate.render(config, source="/tmp/config.yaml", generated_at=STAMP)
    second = migrate.render(config, source="/tmp/config.yaml", generated_at=STAMP)

    assert first == second
    assert first.startswith("// Generated by `asksage-proxy`")
    assert parse_jsonc(first) == config


def test_render_documents_the_offline_fallback() -> None:
    text = migrate.render(
        migrate.build_config({"api_key": "k"}, model_ids=[]),
        source="/tmp/config.yaml",
        generated_at=STAMP,
    )

    assert "shims.paths" in text
    assert "ASKSAGE_TOKEN_EMAIL" in text


def test_no_keys_means_no_providers_and_no_models() -> None:
    config = migrate.build_config({}, model_ids=["m"])

    assert config["providers"] == {}
    assert config["models"] == {}
